-- ============================================================
-- BANQUITO - Core bancario (modulo de credito)
-- Motor: MySQL 8      Esquema: banquito
-- Tablas del Core segun el enunciado: CLIENTE, CUENTA, MOVIMIENTO
-- Tablas agregadas para el modulo de credito: CREDITO, AMORTIZACION
-- ============================================================
CREATE DATABASE IF NOT EXISTS banquito CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE banquito;

DROP TABLE IF EXISTS AMORTIZACION;
DROP TABLE IF EXISTS CREDITO;
DROP TABLE IF EXISTS MOVIMIENTO;
DROP TABLE IF EXISTS CUENTA;
DROP TABLE IF EXISTS CLIENTE;

CREATE TABLE CLIENTE (
    COD_CLIENTE      INT          NOT NULL,
    CEDULA           VARCHAR(100) NOT NULL,
    NOMBRE           VARCHAR(100) NOT NULL,
    GENERO           VARCHAR(1)   NOT NULL,          -- M o F
    FECHA_NACIMIENTO DATE         NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (COD_CLIENTE),
    CONSTRAINT UQ_CLIENTE_CEDULA UNIQUE (CEDULA),
    CONSTRAINT CK_CLIENTE_GENERO CHECK (GENERO IN ('M', 'F'))
);

CREATE TABLE CUENTA (
    NUM_CUENTA  VARCHAR(8)    NOT NULL,
    COD_CLIENTE INT           NOT NULL,
    SALDO       NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_CUENTA PRIMARY KEY (NUM_CUENTA),
    CONSTRAINT FK_CUENTA_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE (COD_CLIENTE)
);

CREATE TABLE MOVIMIENTO (
    COD_MOVIMIENTO INT           NOT NULL AUTO_INCREMENT,
    NUM_CUENTA     VARCHAR(8)    NOT NULL,
    TIPO           VARCHAR(3)    NOT NULL,           -- DEP (deposito) o RET (retiro)
    VALOR          NUMERIC(10,2) NOT NULL,
    FECHA          DATE          NOT NULL,
    CONSTRAINT PK_MOVIMIENTO PRIMARY KEY (COD_MOVIMIENTO),
    CONSTRAINT FK_MOVIMIENTO_CUENTA FOREIGN KEY (NUM_CUENTA) REFERENCES CUENTA (NUM_CUENTA),
    CONSTRAINT CK_MOVIMIENTO_TIPO CHECK (TIPO IN ('DEP', 'RET'))
);

CREATE TABLE CREDITO (
    COD_CREDITO     INT           NOT NULL AUTO_INCREMENT,
    COD_CLIENTE     INT           NOT NULL,
    MONTO_CREDITO   NUMERIC(10,2) NOT NULL,
    PLAZO_MESES     INT           NOT NULL,
    TASA_ANUAL      NUMERIC(5,2)  NOT NULL,
    CUOTA_FIJA      NUMERIC(10,2) NOT NULL,
    FECHA_INICIO    DATE          NOT NULL,
    FECHA_FIN       DATE          NOT NULL,
    ESTADO          VARCHAR(10)   NOT NULL,          -- ACTIVO o CANCELADO
    SALDO_PENDIENTE NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_CREDITO PRIMARY KEY (COD_CREDITO),
    CONSTRAINT FK_CREDITO_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE (COD_CLIENTE),
    CONSTRAINT CK_CREDITO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'CANCELADO')),
    CONSTRAINT CK_CREDITO_PLAZO CHECK (PLAZO_MESES BETWEEN 3 AND 18)
);

CREATE TABLE AMORTIZACION (
    COD_AMORTIZACION INT           NOT NULL AUTO_INCREMENT,
    COD_CREDITO      INT           NOT NULL,
    NUM_CUOTA        INT           NOT NULL,
    FECHA_PAGO       DATE          NOT NULL,
    VALOR_CUOTA      NUMERIC(10,2) NOT NULL,
    INTERES_PAGADO   NUMERIC(10,2) NOT NULL,
    CAPITAL_PAGADO   NUMERIC(10,2) NOT NULL,
    SALDO            NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_AMORTIZACION PRIMARY KEY (COD_AMORTIZACION),
    CONSTRAINT UQ_AMORTIZACION_CUOTA UNIQUE (COD_CREDITO, NUM_CUOTA),
    CONSTRAINT FK_AMORTIZACION_CREDITO FOREIGN KEY (COD_CREDITO) REFERENCES CREDITO (COD_CREDITO)
);

CREATE INDEX IX_MOVIMIENTO_CUENTA_FECHA ON MOVIMIENTO (NUM_CUENTA, FECHA);
CREATE INDEX IX_CREDITO_CLIENTE ON CREDITO (COD_CLIENTE, ESTADO);
