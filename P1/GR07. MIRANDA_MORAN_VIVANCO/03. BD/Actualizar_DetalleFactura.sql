-- Para una base comercializadora que ya existe (creada antes de las ventas con varios celulares):
-- crea la tabla de detalle y pasa a ella las facturas anteriores (una linea por factura). Ejecutar una sola vez.
USE comercializadora;
CREATE TABLE IF NOT EXISTS DETALLE_FACTURA (
    NUM_FACTURA     INT           NOT NULL,
    NUM_LINEA       INT           NOT NULL,
    COD_TELEFONO    INT           NOT NULL,
    CANTIDAD        INT           NOT NULL,
    PRECIO_UNITARIO NUMERIC(10,2) NOT NULL,
    CONSTRAINT PK_DETALLE_FACTURA PRIMARY KEY (NUM_FACTURA, NUM_LINEA),
    CONSTRAINT FK_DETALLE_FACTURA FOREIGN KEY (NUM_FACTURA) REFERENCES FACTURA (NUM_FACTURA),
    CONSTRAINT FK_DETALLE_TELEFONO FOREIGN KEY (COD_TELEFONO) REFERENCES TELEFONO (COD_TELEFONO),
    CONSTRAINT CK_DETALLE_CANTIDAD CHECK (CANTIDAD > 0)
);
INSERT INTO DETALLE_FACTURA (NUM_FACTURA, NUM_LINEA, COD_TELEFONO, CANTIDAD, PRECIO_UNITARIO)
SELECT f.NUM_FACTURA, 1, f.COD_TELEFONO, 1, f.PRECIO_LISTA FROM FACTURA f
WHERE NOT EXISTS (SELECT 1 FROM DETALLE_FACTURA d WHERE d.NUM_FACTURA = f.NUM_FACTURA);
