-- ============================================================
-- COMERCIALIZADORA DE TELEFONOS CELULARES - facturacion (sin inventario)
-- Motor: MySQL 8      Esquema: comercializadora
-- La tabla TELEFONO es solo el catalogo de equipos a la venta.
-- ============================================================
CREATE DATABASE IF NOT EXISTS comercializadora CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE comercializadora;

DROP TABLE IF EXISTS FACTURA;
DROP TABLE IF EXISTS TELEFONO;
DROP TABLE IF EXISTS CLIENTE;

CREATE TABLE CLIENTE (
    COD_CLIENTE INT          NOT NULL AUTO_INCREMENT,
    CEDULA      VARCHAR(20)  NOT NULL,
    NOMBRE      VARCHAR(100) NOT NULL,
    CONSTRAINT PK_CLIENTE PRIMARY KEY (COD_CLIENTE),
    CONSTRAINT UQ_CLIENTE_CEDULA UNIQUE (CEDULA)
);

CREATE TABLE TELEFONO (
    COD_TELEFONO INT           NOT NULL AUTO_INCREMENT,
    MARCA        VARCHAR(50)   NOT NULL,
    MODELO       VARCHAR(100)  NOT NULL,
    PRECIO       NUMERIC(10,2) NOT NULL,
    DISPONIBLE   TINYINT(1)    NOT NULL DEFAULT 1,     -- 1 = a la venta, 0 = retirado del catalogo
    CONSTRAINT PK_TELEFONO PRIMARY KEY (COD_TELEFONO),
    CONSTRAINT CK_TELEFONO_PRECIO CHECK (PRECIO > 0)
);

CREATE TABLE FACTURA (
    NUM_FACTURA  INT           NOT NULL AUTO_INCREMENT,
    FECHA        DATETIME      NOT NULL,
    COD_CLIENTE  INT           NOT NULL,
    COD_TELEFONO INT           NOT NULL,
    FORMA_PAGO   VARCHAR(10)   NOT NULL,               -- EFECTIVO o CREDITO
    PRECIO_LISTA NUMERIC(10,2) NOT NULL,
    DESCUENTO    NUMERIC(10,2) NOT NULL,
    TOTAL        NUMERIC(10,2) NOT NULL,
    NUM_CUOTAS   INT           NULL,                   -- solo para CREDITO
    COD_CREDITO  INT           NULL,                   -- codigo del credito en el Core del banco
    CONSTRAINT PK_FACTURA PRIMARY KEY (NUM_FACTURA),
    CONSTRAINT FK_FACTURA_CLIENTE FOREIGN KEY (COD_CLIENTE) REFERENCES CLIENTE (COD_CLIENTE),
    CONSTRAINT FK_FACTURA_TELEFONO FOREIGN KEY (COD_TELEFONO) REFERENCES TELEFONO (COD_TELEFONO),
    CONSTRAINT CK_FACTURA_FORMA CHECK (FORMA_PAGO IN ('EFECTIVO', 'CREDITO'))
);

CREATE INDEX IX_FACTURA_CLIENTE ON FACTURA (COD_CLIENTE);
